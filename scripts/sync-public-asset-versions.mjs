#!/usr/bin/env node
/**
 * Writes mtime cache-bust tokens for public raster assets used in the app.
 * Run on dev start and when watched assets change.
 */
import { existsSync, statSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const outputPath = join(root, "lib/home/public-asset-versions.ts");

/** Public paths (as used in app) keyed by filename for version lookup. */
const WATCHED_ASSETS = ["public/home/hero-bg.jpg"];

function getVersionToken(path) {
  const abs = join(root, path);
  if (!existsSync(abs)) return null;
  return String(Math.floor(statSync(abs).mtimeMs));
}

function buildFile() {
  const versions = {};
  for (const path of WATCHED_ASSETS) {
    const token = getVersionToken(path);
    if (token) versions[basename(path)] = token;
  }

  const body = `// AUTO-GENERATED by scripts/sync-public-asset-versions.mjs — do not edit.
export const PUBLIC_ASSET_VERSIONS = ${JSON.stringify(versions, null, 2)} as const;

export function publicAssetUrl(path: string): string {
  const filename = path.split("/").pop() ?? path;
  const version =
    PUBLIC_ASSET_VERSIONS[filename as keyof typeof PUBLIC_ASSET_VERSIONS];
  return version ? \`\${path}?v=\${version}\` : path;
}
`;

  writeFileSync(outputPath, body);
}

buildFile();
